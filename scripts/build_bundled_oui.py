"""
Build the bundled vendor OUI file (scrutics/classifier/ics_oui.txt) from IEEE registry files.

The four CSV files of the IEEE Registration Authority public listing are the input, downloaded
by hand beforehand; this script never uses the network:

    MA-L  https://standards-oui.ieee.org/oui/oui.csv
    MA-M  https://standards-oui.ieee.org/oui28/mam.csv
    MA-S  https://standards-oui.ieee.org/oui36/oui36.csv
    IAB   https://standards-oui.ieee.org/iab/iab.csv

Usage:
    python scripts/build_bundled_oui.py --ma-l oui.csv --ma-m mam.csv --ma-s oui36.csv \\
        --iab iab.csv --retrieved 2026-10-10 --out scrutics/classifier/ics_oui.txt

Selection: an assignment is written when classify_vendor gives its registered organisation a
vendor class (OT, NEUTRAL or IT), so the bundled data and the vendor matcher agree. Blocks held by
the IEEE Registration Authority itself (the shared blocks that MA-M, MA-S and IAB assignments are
carved from) are never written: a MAC in such a block resolves to the holder of its smaller block,
or to nothing. Organisation names are written exactly as the registry gives them.
"""

import argparse
import csv
import hashlib
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from scrutics.classifier.oui import VENDOR_CLASS_UNKNOWN, classify_vendor  # noqa: E402
from scrutics.csv_input import allow_large_fields  # noqa: E402

ATTRIBUTION = "Vendor assignments from the IEEE Registration Authority registry"
REGISTRATION_AUTHORITY = "IEEE Registration Authority"
COLUMNS = ("Registry", "Assignment", "Organization Name")
# Registry name -> number of hexadecimal digits in its assignments
REGISTRIES = {"MA-L": 6, "MA-M": 7, "MA-S": 9, "IAB": 9}


class RegistryError(ValueError):
    """An input file cannot be used; nothing is written."""


def _sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def read_registry(path, registry):
    """(assignment, organisation) rows of one registry CSV file, validated."""
    digits = REGISTRIES[registry]
    rows = []
    allow_large_fields()
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        missing = [c for c in COLUMNS if c not in (reader.fieldnames or [])]
        if missing:
            raise RegistryError(f"{path}: missing column(s) {', '.join(missing)}")
        for line, row in enumerate(reader, start=2):
            if row["Registry"].strip() != registry:
                raise RegistryError(f"{path} line {line}: registry {row['Registry']!r}, expected {registry}")
            assignment = row["Assignment"].strip().upper()
            if len(assignment) != digits or any(c not in "0123456789ABCDEF" for c in assignment):
                raise RegistryError(f"{path} line {line}: assignment {row['Assignment']!r} is not "
                                    f"{digits} hexadecimal digits")
            name = row["Organization Name"].strip()
            if any(c in name for c in "\t\r\n"):
                raise RegistryError(f"{path} line {line}: organisation name contains a tab or line break")
            rows.append((assignment, name))
    return rows


def format_prefix(assignment):
    """00-50-C2 (MA-L), 00-50-C2-D (MA-M) or 00-50-C2-12-3 (MA-S, IAB)."""
    pairs = [assignment[i:i + 2] for i in range(0, len(assignment), 2)]
    return "-".join(pairs)


def build(inputs, retrieved):
    """
    The bundled file as text. `inputs` maps a registry name to its CSV path. Raises RegistryError
    if an input cannot be used or one prefix is assigned to two different organisations.
    """
    selected = {}            # assignment -> (registry, organisation, vendor class)
    counts = {}
    for registry in REGISTRIES:
        for assignment, name in read_registry(inputs[registry], registry):
            if name == REGISTRATION_AUTHORITY or not name:
                continue
            vclass = classify_vendor(name)
            if vclass == VENDOR_CLASS_UNKNOWN:
                continue
            previous = selected.get(assignment)
            if previous is not None and previous[1] != name:
                raise RegistryError(f"assignment {assignment} is held by both {previous[1]!r} and {name!r}")
            selected[assignment] = (registry, name, vclass)
            counts[(registry, vclass)] = counts.get((registry, vclass), 0) + 1

    lines = [f"# {ATTRIBUTION}",
             "# Generated by scripts/build_bundled_oui.py; do not edit by hand.",
             f"# Retrieved {retrieved} from https://standards-oui.ieee.org/:"]
    for registry, path in inputs.items():
        lines.append(f"#   {registry}: {os.path.basename(path)} SHA-256 {_sha256(path)}")
    lines.append("# Selection: assignments whose registered organisation the vendor matcher classifies "
                 "OT, NEUTRAL or IT; blocks held by the IEEE Registration Authority are not listed.")
    for registry in REGISTRIES:
        per_class = ", ".join(f"{c} {counts[(registry, c)]}" for c in ("OT", "NEUTRAL", "IT")
                              if counts.get((registry, c)))
        lines.append(f"#   {registry}: {per_class or 'none'}")
    lines.append("# Organisation names are as registered; the registry holder is not necessarily the "
                 "maker of the device.")
    lines.append("")
    # Sorted by prefix, then length, so the output is the same whatever the input order
    for assignment in sorted(selected, key=lambda a: (a, len(a))):
        registry, name, _ = selected[assignment]
        lines.append(f"{format_prefix(assignment)}   (hex)\t\t{name}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--ma-l", required=True, help="MA-L registry CSV (oui.csv)")
    parser.add_argument("--ma-m", required=True, help="MA-M registry CSV (mam.csv)")
    parser.add_argument("--ma-s", required=True, help="MA-S registry CSV (oui36.csv)")
    parser.add_argument("--iab", required=True, help="IAB registry CSV (iab.csv)")
    parser.add_argument("--retrieved", required=True, help="date the files were downloaded (YYYY-MM-DD)")
    parser.add_argument("--out", required=True, help="file to write")
    args = parser.parse_args(argv)
    inputs = {"MA-L": args.ma_l, "MA-M": args.ma_m, "MA-S": args.ma_s, "IAB": args.iab}
    try:
        text = build(inputs, args.retrieved)
    except (RegistryError, OSError) as exc:
        print(f"[!] {exc}", file=sys.stderr)
        return 1
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"[+] Wrote {text.count('(hex)')} assignments to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
