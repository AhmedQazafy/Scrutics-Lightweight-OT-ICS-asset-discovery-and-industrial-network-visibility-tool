// Runs the topology page's own graph script with a stub DOM and canvas and prints, for each run, what
// the canvas showed once the layout settled ("open") and after pressing F ("fit"), as JSON.
// Usage: node topology_layout_harness.js RUNS_FILE
// RUNS_FILE: {"script": "...", "runs": [{"data": "...", "window": [width, height]}, ...]}
// The page's side panel takes 280 px of the window width and the header 48 px of its height.
"use strict";
const fs = require("fs");
const vm = require("vm");

const PANEL_WIDTH = 280;
const HEADER_HEIGHT = 48;
const HINT_TEXT_WIDTH = 650;
const HINT_LINE_HEIGHT = 15;

// Monospace text is 0.6 font sizes wide per character in this stub
function fontPx(font) { return parseFloat(String(font || "10px").split("px")[0]); }
function textWidth(text, font) { return String(text).length * fontPx(font) * 0.6; }

function runOnce(script, data, windowWidth, windowHeight) {
  const width = windowWidth - PANEL_WIDTH;
  const height = windowHeight - HEADER_HEIGHT;
  let circles = [], curves = [], texts = [], segments = [], pendingRect = null, path = [];
  const state = { font: "10px monospace", textAlign: "start", textBaseline: "alphabetic" };
  const ctx = new Proxy(state, {
    get(target, key) {
      if (key in target) return target[key];
      switch (key) {
        case "clearRect": return () => { circles = []; curves = []; texts = []; segments = []; pendingRect = null; };
        case "measureText": return (text) => ({ width: textWidth(text, target.font) });
        case "beginPath": return () => { path = []; };
        case "arc": return (x, y, r, a0, a1) => { if (Math.abs((a1 - a0) - Math.PI * 2) < 1e-9) circles.push({ x, y, r }); };
        case "moveTo": return (x, y) => { path.push(["M", x, y]); };
        case "lineTo": return (x, y) => { path.push(["L", x, y]); };
        case "quadraticCurveTo": return (cx, cy, x, y) => {
          const last = path[path.length - 1];
          curves.push({ x0: last[last.length - 2], y0: last[last.length - 1], cx, cy, x, y });
          path.push(["Q", x, y]); };
        case "stroke": return () => {
          // A path of one straight line is a leader line
          if (path.length === 2 && path[0][0] === "M" && path[1][0] === "L") {
            segments.push({ x0: path[0][1], y0: path[0][2], x1: path[1][1], y1: path[1][2] });
          } };
        case "roundRect": case "rect": return (x, y, w, h) => { pendingRect = { x, y, w, h }; };
        case "fillText": return (text, x, y) => {
          texts.push({ text: String(text), x, y, font: target.font, align: target.textAlign,
                       baseline: target.textBaseline, width: textWidth(text, target.font), box: pendingRect });
          pendingRect = null; };
        default: return () => {};
      }
    },
    set(target, key, value) { target[key] = value; return true; },
  });

  // The hint line is centred on the window, at most half the window wide, 10 px above the bottom
  const hintWidth = Math.min(HINT_TEXT_WIDTH, windowWidth / 2);
  const hintHeight = Math.ceil(HINT_TEXT_WIDTH / hintWidth) * HINT_LINE_HEIGHT;
  const hintRect = { left: windowWidth / 2 - hintWidth / 2, right: windowWidth / 2 + hintWidth / 2,
                     top: windowHeight - 10 - hintHeight, bottom: windowHeight - 10,
                     width: hintWidth, height: hintHeight };

  function element(id) {
    return { id, textContent: "", innerHTML: "", style: {}, classList: { add() {}, remove() {} },
             appendChild() {}, addEventListener() {},
             getBoundingClientRect: () => (id === "hint" ? hintRect : { left: 0, top: 0, right: 0, bottom: 0, width: 0, height: 0 }) };
  }
  const elements = {};
  const canvas = Object.assign(element("topology"), {
    getContext: () => ctx,
    getBoundingClientRect: () => ({ left: 0, top: HEADER_HEIGHT, right: width, bottom: HEADER_HEIGHT + height, width, height }),
  });
  const windowHandlers = {};
  const frames = [];
  const captured = {};
  const context = vm.createContext({
    document: {
      getElementById(id) {
        if (id === "graph-data") return { textContent: data };
        if (id === "topology") return canvas;
        return elements[id] || (elements[id] = element(id));
      },
      createElement: () => element(""),
    },
    window: {
      devicePixelRatio: 1,
      addEventListener(type, handler) { (windowHandlers[type] = windowHandlers[type] || []).push(handler); },
    },
    requestAnimationFrame: (fn) => { frames.push(fn); },
    XLSX: {},
    __graphText: data,
    __captured: captured,
  });
  vm.runInContext(
    "(function () { const parse = JSON.parse; JSON.parse = function (t, r) { const v = parse(t, r); " +
    "if (t === __graphText) __captured.graph = v; return v; }; })();", context);
  // The script is the page's own graph script, generated by the code under test
  vm.runInContext(script, context, { filename: "topology_graph_script.js" });

  let count = 0;
  while (frames.length && count < 20000) { frames.shift()(); count++; }
  const banner = () => {
    const el = elements["offscreen-alert"];
    return { display: el ? (el.style.display || "") : "", text: el ? el.innerHTML : "" };
  };
  const snapshot = () => ({
    circles, curves, texts, segments, banner: banner(),
    positions: captured.graph.nodes.map((n) => [n.id, n.x, n.y]),
  });
  const open = snapshot();
  (windowHandlers.keydown || []).forEach((h) => h({ key: "f", target: { tagName: "CANVAS" } }));
  const fit = snapshot();
  return { settled: frames.length === 0, frames: count, canvas: [width, height],
           overlays: [{ x0: hintRect.left, y0: hintRect.top - HEADER_HEIGHT, x1: hintRect.right, y1: hintRect.bottom - HEADER_HEIGHT }],
           open, fit };
}

const input = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const out = input.runs.map((r) => runOnce(input.script, r.data, r.window[0], r.window[1]));
process.stdout.write(JSON.stringify(out));
